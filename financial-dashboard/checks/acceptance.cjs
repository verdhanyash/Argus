const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
fs.mkdirSync(path.join(root,'.artifacts'),{recursive:true});
const url=pathToFileURL(path.join(root,'dist/index.html')).href;
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:900},offline:true});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url);await page.locator('.ninecard').first().waitFor();
 assert.equal(await page.locator('.nine .ninecard').count(),9);
 assert.deepEqual(await page.locator('.app-sidebar nav a').allTextContents(),['Overview','AWS costs','Scale model']);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight),900);
 await page.locator('#market').getByRole('heading').click();
 await page.getByRole('dialog',{name:'Global Sentiment Intelligence Market',exact:true}).waitFor();
 assert.ok(await page.evaluate(()=>Boolean(document.elementFromPoint(720,450)?.closest('[role=dialog]'))));
 await page.keyboard.press('Escape');
 await page.getByRole('link',{name:'AWS costs',exact:true}).click();
 await page.locator('.aws-charts').waitFor();
 await page.getByRole('button',{name:'USD',exact:true}).click();
 assert.equal(await page.locator('.aws-charts [data-chart]').count(),3);
 assert.equal(await page.getByText('Retained vs removed · monthly list-price equivalents',{exact:true}).count(),0);
 await page.getByRole('button',{name:'Latest console ▾',exact:true}).click();
 await page.getByRole('menuitem',{name:'Single day',exact:true}).click();
 assert.equal(await page.getByLabel('UTC billing day',{exact:true}).inputValue(),'2026-11-14');
 assert.match(await page.locator('#aws-service-mix .ringbox').innerText(),/23.85/);
 await page.screenshot({path:path.join(root,'.artifacts','orange-aws.png'),fullPage:true});
 for(const width of [1280,1024,390]){
  await page.setViewportSize({width,height:900});
  await page.waitForFunction(w=>document.documentElement.scrollWidth<=w,width,{timeout:3000});
  assert.ok(await page.evaluate(w=>document.documentElement.scrollWidth<=w,width),'Horizontal overflow at '+width);
 }
 await page.setViewportSize({width:1440,height:900});
 await page.getByRole('link',{name:'Scale model',exact:true}).click();
 await page.getByLabel('Analysis time basis',{exact:true}).selectOption('run18');
 assert.equal(await page.locator('input[type=number]').count(),0);
 await page.getByRole('link',{name:'Overview',exact:true}).click();
 await page.getByLabel('Expand AWS Cost by Service',{exact:true}).click();
 await page.getByRole('dialog',{name:'AWS Cost by Service',exact:true}).waitFor();
 await page.getByLabel('Close AWS Cost by Service',{exact:true}).click();
 await page.screenshot({path:path.join(root,'.artifacts','orange-overview.png')});
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: three sidebar pages, removed chart/pages, simplified AWS billing graphs, daily selector, accessible tooltips, currency, zoom, responsive layout and offline build.');
})().catch(e=>{console.error(e);process.exit(1)});
